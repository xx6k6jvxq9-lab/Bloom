export function buildSpectatorPromptStyleGuide(options: {
  hasFictionAngle: boolean;
}) {
  const fictionRule = options.hasFictionAngle
    ? '同人文/短文向可以出现 1 到 2 条片段体、日记体、伪连载体，但仍然要保留论坛帖子的壳，不要写成脱离论坛语境的纯小说。'
    : '如果当前角度里没有同人文/短文向，就不要硬写片段体小说。';

  return [
    '### 镜间写法守则',
    '1. 不同题材要真的分开，不要 5 条都像一种人在写。',
    '2. 目击帖：像刚撞见就忍不住开楼，重点是现场感和旁人反应。',
    '3. 复盘帖：像有人在顺时间线、扒细节、拼证据，但语气还是论坛楼主，不是分析报告。',
    '4. 匿名瓜：像听来半耳朵风声，带一点犹豫、保留和楼里试探。',
    '5. 押股/站队楼：像楼里人真的会吵起来，会各自端证据，不要像总结帖。',
    '6. 情绪帖：可以半夜上头、嘴硬、发疯、阴阳、叠甲，但仍然是论坛用户发帖。',
    '7. 聊天转述/值班记录/时间线帖：可以用时间点、碎句、简短分段、伪记录感。',
    fictionRule,
    '8. 所有帖子都要避免“这段关系体现了”“从这个角度来看”这类解释腔。',
    '9. 评论要更像楼里人：可以很短、可以接梗、可以偏心、可以吐槽、可以只补半句。',
    '10. 允许带一点文气，但不能把整板块写成同一种文风。',
  ].join('\n');
}
